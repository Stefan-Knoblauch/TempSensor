#!/usr/bin/env python3
"""Run every desk-only verification activity and write verification/report.md.

  1. Analysis models (models/*.py)       -> numeric checks against requirements
  2. Firmware unit/HIL tests (make test) -> pass/fail
  3. Platform codec tests (unittest)     -> pass/fail, incl. firmware vector cross-check
Exit status is non-zero if any adopted-design check or test fails.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "models"))

import energy, fem_magnet, fem_thermal, fit, lora, mass, modal, retention, thermal  # noqa: E402
from common import checks_table  # noqa: E402


def sh(cmd, cwd):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    return r.returncode, (r.stdout + r.stderr).strip()


def tail(text, n=15):
    return "\n".join(text.splitlines()[-n:])


def main():
    sections, failures, all_checks = [], [], []
    results = [lora.run(), energy.run(), fem_thermal.run(), thermal.run(), fem_magnet.run(),
               retention.run(), modal.run(), mass.run(),
               fit.run(os.path.join(HERE, "fit_profiles.svg"))]
    for res in results:
        sections.append(res["md"])
        rejected = res.get("rejected", set())
        for c in res["checks"]:
            if c.what in rejected:
                continue                     # shown to justify a decision, not a design check
            all_checks.append(c)
            if not c.ok:
                failures.append(f"{c.req}: {c.what}")

    fw_rc, fw_out = sh(["make", "-s", "test"], os.path.join(ROOT, "firmware"))
    if fw_rc:
        failures.append("firmware tests")
    pf_rc, pf_out = sh([sys.executable, "-m", "unittest", "-v", "test_codec"],
                       os.path.join(ROOT, "platform"))
    if pf_rc:
        failures.append("platform tests")

    by_req = {}
    for c in all_checks:
        by_req.setdefault(c.req, []).append(c.ok)
    summary = "\n".join(f"| {r} | {len(v)} | {'PASS' if all(v) else 'FAIL'} |"
                        for r, v in sorted(by_req.items()))
    report = [
        "# Tier 1 desk-only verification report",
        "",
        "Generated by `verification/run_all.py`. Do not edit by hand.",
        "",
        f"**Overall: {'PASS' if not failures else 'FAIL'}** "
        f"({len(all_checks)} analysis checks, firmware tests {'PASS' if not fw_rc else 'FAIL'}, "
        f"platform tests {'PASS' if not pf_rc else 'FAIL'})",
        "",
        "## Analysis checks by requirement",
        "",
        "| Req | Checks | Result |",
        "|---|---|---|",
        summary,
        "",
        "## Analysis detail",
        "",
        *sections,
        "## Firmware tests (`make test`)",
        "",
        "```",
        tail(fw_out, 25),
        "```",
        "",
        "## Platform tests (`python -m unittest test_codec`)",
        "",
        "```",
        tail(pf_out, 25),
        "```",
        "",
    ]
    if failures:
        report += ["## Failures", ""] + [f"- {f}" for f in failures] + [""]
    with open(os.path.join(HERE, "report.md"), "w") as f:
        f.write("\n".join(report))
    print("\n".join(failures) if failures else "ALL PASS")
    print(f"analysis checks: {len(all_checks)}; firmware rc={fw_rc}; platform rc={pf_rc}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
